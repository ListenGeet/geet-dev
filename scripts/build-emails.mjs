// Bundles emails/templates into api/src/lib/email/templates.generated.ts so the API never reads files at
// runtime (Vercel only ships what is imported). Run: npm run emails:build. A test fails when it is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'emails', 'templates');
const manifest = JSON.parse(readFileSync(join(dir, '_manifest.json'), 'utf8'));

const templates = {};
for (const name of Object.keys(manifest).sort()) {
  templates[name] = {
    subject: manifest[name].subject,
    from: manifest[name].from,
    html: readFileSync(join(dir, `${name}.html`), 'utf8'),
    text: readFileSync(join(dir, `${name}.txt`), 'utf8'),
  };
}

const out =
  '// Generated by scripts/build-emails.mjs from emails/templates. Do not edit.\n' +
  `export const templates = ${JSON.stringify(templates, null, 1)} as const;\n`;
writeFileSync(join(root, 'api', 'src', 'lib', 'email', 'templates.generated.ts'), out);
console.log(`emails:build: ${Object.keys(templates).length} templates`);
